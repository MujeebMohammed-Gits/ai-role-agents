"""LLM client abstraction.

Provides a single ``complete`` coroutine the agents call. Defaults to a
deterministic mock so the whole mesh runs without any API keys. To wire
a real provider, subclass ``LLMClient`` and register it in
``orchestrator.py`` (or set ``LLM_PROVIDER=openai|anthropic``).
"""

from __future__ import annotations

import hashlib
import logging
import re
from typing import Optional

from collections.abc import AsyncIterator

logger = logging.getLogger("core.llm_client")


class LLMClient:
    async def complete(
        self,
        system_prompt: str,
        messages: list[dict],
        temperature: float = 0.7,
        max_tokens: int = 1000,
    ) -> str:
        raise NotImplementedError

    async def stream_complete(
        self,
        system_prompt: str,
        messages: list[dict],
        temperature: float = 0.7,
        max_tokens: int = 1000,
    ):
        """Yield text chunks as they are produced by the provider.

        Default implementation falls back to :meth:`complete` and yields the
        full response as a single chunk. Subclasses that support native
        streaming should override this.
        """
        response = await self.complete(
            system_prompt, messages, temperature=temperature, max_tokens=max_tokens
        )
        if response:
            yield response


class MockLLMClient(LLMClient):
    """Deterministic stand-in. Produces plausible, role-aware responses
    without calling any external API. Replace with a real provider for
    production use."""

    def _seed(self, text: str) -> int:
        return int(hashlib.sha256(text.encode()).hexdigest()[:8], 16)

    def _role_tone(self, system_prompt: str) -> str:
        lower = system_prompt.lower()
        if "delivery" in lower:
            return "delivery-focused"
        if "agile coach" in lower:
            return "coaching"
        if "scrum" in lower:
            return "facilitative"
        if "product owner" in lower:
            return "backlog-focused"
        if "product manager" in lower:
            return "product-led"
        if "business analyst" in lower:
            return "analytical"
        if "user research" in lower:
            return "research-led"
        if "devops" in lower:
            return "operations-focused"
        if "sre" in lower:
            return "reliability-focused"
        if "platform" in lower:
            return "platform-focused"
        if "programme" in lower:
            return "programme-focused"
        if "consultant" in lower:
            return "advisory"
        return "professional"

    async def complete(
        self,
        system_prompt: str,
        messages: list[dict],
        temperature: float = 0.7,
        max_tokens: int = 1000,
    ) -> str:
        user_text = ""
        for m in reversed(messages):
            if m.get("role") == "user":
                user_text = m.get("content", "")
                break

        tone = self._role_tone(system_prompt)
        seed = self._seed(system_prompt + user_text)
        rng = seed % 100

        # Compose a structured, helpful response that references the query.
        lines = [
            f"[{tone.title()} agent]",
            "",
            f"Thank you for your request: “{user_text[:120]}"
            f"{'…' if len(user_text) > 120 else ''}”",
            "",
            "Based on the system boundaries and context available to me, here is my assessment:",
            "",
            "• **Situation**: I have received your query and am operating within the "
            f"boundaries of the {tone} role.",
            "• **Analysis**: Your request touches on concerns this role owns. "
            "The full analysis below applies the role's principles and tools.",
            "• **Recommendation**: Proceed with the actions outlined below, "
            "and involve the stakeholders this role is accountable to.",
            "",
            "---",
            "",
            "**Suggested next steps:**",
            "1. Confirm the objective and success criteria with stakeholders.",
            "2. Break the work into owned, trackable items.",
            "3. Establish review checkpoints and escalation paths.",
            "",
            f"_Note: This response was generated by the mock LLM client "
            f"(LLM_PROVIDER=mock). Set LLM_PROVIDER to openai or anthropic and "
            f"provide the corresponding API key for real model output._",
        ]
        return "\n".join(lines)


def build_client(provider: str, model: str, **kwargs) -> LLMClient:
    provider = (provider or "mock").lower()
    if provider == "mock":
        return MockLLMClient()
    if provider == "openai":
        try:
            from openai import AsyncOpenAI  # type: ignore
        except ImportError as exc:  # pragma: no cover
            raise RuntimeError(
                "openai package not installed; `pip install openai` or use LLM_PROVIDER=mock"
            ) from exc
        import os
        _api_key = (kwargs.get("openai_api_key") or os.environ.get("OPENAI_API_KEY") or "proxy").strip()
        _default_base = "https://nvidia.com" if _api_key.startswith("nvapi-") else "http://localhost:8082/v1"
        _base_url = (
            os.environ.get("OPENAI_BASE_URL")
            or os.environ.get("OPENAI_API_BASE")
            or kwargs.get("openai_api_base")
            or _default_base
        ).strip()
        return _OpenAILLMClient(
            AsyncOpenAI(api_key=_api_key, base_url=_base_url, timeout=90.0), model
        )
    if provider == "anthropic":
        try:
            import anthropic  # type: ignore
        except ImportError as exc:  # pragma: no cover
            raise RuntimeError(
                "anthropic package not installed; `pip install anthropic` or use LLM_PROVIDER=mock"
            ) from exc
        import os
        _anth_base = os.environ.get("ANTHROPIC_BASE_URL") or "http://localhost:8082"
        _anth_key = (
            kwargs.get("anthropic_api_key")
            or os.environ.get("ANTHROPIC_API_KEY")
            or "proxy-handled"
        )
        return _AnthropicLLMClient(
            anthropic.AsyncAnthropic(api_key=_anth_key, base_url=_anth_base, timeout=120.0), model
        )
    return MockLLMClient()


class _OpenAILLMClient(LLMClient):
    def __init__(self, client: object, model: str) -> None:
        self._client = client
        self._model = model

    async def complete(
        self,
        system_prompt: str,
        messages: list[dict],
        temperature: float = 0.7,
        max_tokens: int = 1000,
    ) -> str:
        chat = [{"role": "system", "content": system_prompt}] + messages
        resp = await self._client.chat.completions.create(
            model=self._model,
            messages=chat,
            max_tokens=max_tokens,
        )
        return resp.choices[0].message.content or ""



    async def stream_complete(
        self,
        system_prompt: str,
        messages: list[dict],
        temperature: float = 0.7,
        max_tokens: int = 4096,
    ):
        full_messages = [{"role": "system", "content": system_prompt}] + [
            m for m in messages if m.get("role") != "system"
        ]
        try:
            stream = await self._client.chat.completions.create(
                model=self._model,
                messages=full_messages,
                temperature=temperature,
                max_tokens=max_tokens,
                stream=True,
            )
        except Exception as exc:
            cause = getattr(exc, "__cause__", None) or exc
            raise RuntimeError(f"LLM API failed ({self._client.base_url} | model={self._model}): {type(cause).__name__}: {cause}") from exc
        async for chunk in stream:
            if chunk.choices and chunk.choices[0].delta and chunk.choices[0].delta.content:
                yield chunk.choices[0].delta.content

class _AnthropicLLMClient(LLMClient):
    def __init__(self, client: object, model: str) -> None:
        self._client = client
        self._model = model

    async def complete(
        self,
        system_prompt: str,
        messages: list[dict],
        temperature: float = 0.7,
        max_tokens: int = 4096,
    ) -> str:
        system_msgs = [m for m in messages if m.get("role") == "system"]
        user_msgs = [m for m in messages if m.get("role") != "system"]
        resp = await self._client.messages.create(
            model=self._model,
            system=system_prompt + "\n" + "\n".join(m.get("content", "") for m in system_msgs),
            messages=user_msgs,
            max_tokens=max_tokens,
        )
        text_blocks: list[str] = []
        for block in resp.content:
            block_type = getattr(block, "type", "")
            if block_type == "text":
                text_blocks.append(getattr(block, "text", ""))
            # ``thinking`` blocks are never surfaced to the caller.
        response = "".join(text_blocks)
        if not response:
            # Retry once with thinking disabled so a reasoning model that
            # exhausted its budget thinking still returns a clean text answer.
            retry = await self._client.messages.create(
                model=self._model,
                system=system_prompt + "\n" + "\n".join(m.get("content", "") for m in system_msgs),
                messages=user_msgs,
                max_tokens=max_tokens,
                thinking={"type": "disabled"},
            )
            text_blocks = [
                getattr(b, "text", "") for b in retry.content if getattr(b, "type", "") == "text"
            ]
            response = "".join(text_blocks)
        if not response:
            raise RuntimeError(
                "Anthropic response contained no text blocks. "
                f"Received {len(resp.content)} content block(s): "
                f"{[getattr(b, 'type', 'unknown') for b in resp.content]}"
            )
        return response

    async def stream_complete(
        self,
        system_prompt: str,
        messages: list[dict],
        temperature: float = 0.7,
        max_tokens: int = 4096,
    ) -> AsyncIterator[str]:
        """Yield text chunks from the Anthropic stream, skipping thinking blocks.

        Only ``block.type == "text_delta"`` chunks are yielded; ``thinking_delta``
        blocks are ignored and never surfaced to the caller. If no
        ``text_delta`` is yielded (reasoning model spent its budget thinking),
        retry once with thinking disabled so only clean, final text is streamed.
        """
        system_msgs = [m for m in messages if m.get("role") == "system"]
        user_msgs = [m for m in messages if m.get("role") != "system"]
        if not user_msgs:
            user_msgs = [{"role": "user", "content": system_prompt}]

        async def _stream(thinking_param=None):
            kwargs = {}
            if thinking_param is not None:
                kwargs["thinking"] = thinking_param
            async with self._client.messages.stream(
                model=self._model,
                system=system_prompt + "\n" + "\n".join(m.get("content", "") for m in system_msgs),
                messages=user_msgs,
                max_tokens=max_tokens,
                **kwargs,
            ) as stream:
                async for event in stream:
                    if event.type != "content_block_delta":
                        continue
                    delta = event.delta
                    delta_type = getattr(delta, "type", "")
                    if delta_type == "text_delta":
                        chunk = getattr(delta, "text", "")
                        if chunk:
                            yield chunk

        any_text = False
        async for chunk in _stream():
            any_text = True
            yield chunk

        if not any_text:
            # Retry once with thinking disabled; the model should now emit text.
            async for chunk in _stream({"type": "disabled"}):
                any_text = True
                yield chunk

        if not any_text:
            raise RuntimeError(
                "Anthropic stream produced no text blocks. "
                "All content blocks were thinking blocks or empty."
            )
